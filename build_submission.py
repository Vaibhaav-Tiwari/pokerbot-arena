def functions(source, names):
    tree = ast.parse(source)
    lines = source.splitlines()
    out = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.Assign)) and (
                getattr(node, "name", None) in names or
                (isinstance(node, ast.Assign) and any(getattr(t, "id", None) in names for t in node.targets))):
            out.append("\n".join(lines[node.lineno - 1:node.end_lineno]))
    return "\n\n\n".join(out)


def strip_module_docstring(source):
    tree = ast.parse(source)
    if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(tree.body[0].value, ast.Constant):
        return "\n".join(source.splitlines()[tree.body[0].end_lineno:])
    return source


